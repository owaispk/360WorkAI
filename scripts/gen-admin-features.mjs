// Regenerates src/WorkAI360.Api/Features/PlatformAdmin/FeatureCatalog.g.cs (the feature registry as /v1/admin/features describes it) from a running
// reference Den (the per-feature author handle is not copied: it names individual people; every feature reports "openwork"). The reference needs a platform admin (see tests/parity/area-platform-admin.mjs): REF_ADMIN_TOKEN=<session token> node scripts/gen-admin-features.mjs
import { writeFileSync } from "node:fs";
const api = process.env.REF_API ?? "http://localhost:8790";
const res = await fetch(`${api}/v1/admin/features`, { headers: { authorization: `Bearer ${process.env.REF_ADMIN_TOKEN}` } });
if (!res.ok) throw new Error(`reference answered ${res.status}: sign in as a platform admin and set REF_ADMIN_TOKEN`);
const { features } = await res.json();
const q = (s) => (s === null || s === undefined ? "null" : JSON.stringify(s));
const rows = features.map((f) => `        new(${q(f.key)}, ${q(f.label)}, ${q(f.description)}, ${q(f.category)}, ${q(f.categoryLabel)}, ${q(f.added)}, ${q(f.since)}, "openwork", ${q(f.docs)}, ${q(f.docsUrl)}, [${f.deployments.map(q).join(", ")}], ${f.default}),`);
const cs = `// <auto-generated>
// Generated from the reference deployment's GET /v1/admin/features (${features.length} features) by scripts/gen-admin-features.mjs. Do not edit by hand.
// </auto-generated>
namespace WorkAI360.Api.Features.PlatformAdmin;

public static partial class FeatureCatalog
{
    public static readonly IReadOnlyList<FeatureInfo> All =
    [
${rows.join("\n")}
    ];
}
`;
writeFileSync(new URL("../src/WorkAI360.Api/Features/PlatformAdmin/FeatureCatalog.g.cs", import.meta.url), cs);
console.log(features.length, "features written");
