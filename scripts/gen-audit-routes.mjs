// Generates src/WorkAI360.Api/Features/OrgAdmin/AuditRoutes.g.cs from the reference's audit route declarations
// (ee/apps/den-api/src/audit/routes/*.ts): every tenant_change / tenant_external route with its action stem and target resource.
//   node scripts/gen-audit-routes.mjs <path to the reference repository>
import fs from "node:fs";
import path from "node:path";

const ref = process.argv[2];
if (!ref) { console.error("usage: node scripts/gen-audit-routes.mjs <reference repo>"); process.exit(2); }
const dir = path.join(ref, "ee/apps/den-api/src/audit/routes");
const rows = new Map();
const add = (r) => { const k = `${r.method} ${r.path}`; if (!rows.has(k)) rows.set(k, r); };

// member()/userOrgs()/route()/handler()/tenant() in org.ts, content.ts, auth.ts, platform.ts, integrations.ts
const generic = /\b(member|userOrgs|route|handler|tenant)\(\s*"(GET|POST|PUT|PATCH|DELETE)"\s*,\s*"([^"]+)"\s*,\s*"([a-z_]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*(null|"[^"]*")/g;
// change()/external() in integrations.ts
const integration = /\b(change|external)\(\s*"(GET|POST|PUT|PATCH|DELETE)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*[A-Za-z_]+\s*,\s*res\("([^"]+)"(?:\s*,\s*"([^"]+)")?\)/g;
for (const file of ["org.ts", "content.ts", "integrations.ts", "auth.ts", "platform.ts"]) {
  const text = fs.readFileSync(path.join(dir, file), "utf8");
  for (const m of text.matchAll(generic)) {
    if (m[4] !== "tenant_change" && m[4] !== "tenant_external") continue;
    add({ method: m[2], path: m[3], cls: m[4], action: m[5], type: m[7], id: m[8] === "null" ? null : m[8].slice(1, -1) });
  }
  for (const m of text.matchAll(integration)) add({ method: m[2], path: m[3], cls: m[1] === "change" ? "tenant_change" : "tenant_external", action: m[4], type: m[5], id: m[6] ?? null });
}
const list = [...rows.values()].sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method));
const q = (s) => (s === null ? "null" : JSON.stringify(s));
const out = `// <auto-generated> by scripts/gen-audit-routes.mjs from the reference's audit route declarations. Do not edit. </auto-generated>
namespace WorkAI360.Api.Features.OrgAdmin;

public static partial class AuditRoutes
{
    /// <summary>Change routes of the reference: method, path (Hono syntax), class, action stem, target resource type, id parameter.</summary>
    public static readonly AuditRouteDeclaration[] Declarations =
    [
${list.map((r) => `        new(${q(r.method)}, ${q(r.path)}, ${q(r.cls)}, ${q(r.action)}, ${q(r.type)}, ${q(r.id)}),`).join("\n")}
    ];
}
`;
fs.writeFileSync("src/WorkAI360.Api/Features/OrgAdmin/AuditRoutes.g.cs", out);
console.log(`${list.length} declarations written`);
