#!/usr/bin/env python3
"""Generates Auth/PermissionCatalog.g.cs from the reference's permission catalog (packages/types/src/den/permissions.ts),
so the rewrite grants each role the same permission keys. Run from the repository root:
    python3 360workai/scripts/gen-permissions.py
"""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
source = (root / "packages/types/src/den/permissions.ts").read_text()
body = source[source.index("export const PERMISSIONS"):]
body = body[:body.index("} as const")]

entries = []
for m in re.finditer(r'^  "([a-z_.]+)": \{\n(.*?)^  \},', body, re.S | re.M):
    key, block = m.group(1), m.group(2)
    label = re.search(r'label: ("(?:[^"\\]|\\.)*")', block)
    default_on = re.search(r'defaultOn: (ADMIN|OWNER_ONLY|\[[^\]]*\])', block)
    if not label or not default_on:
        sys.exit(f"cannot parse {key}")
    raw = default_on.group(1)
    sets = ["admin"] if raw == "ADMIN" else [] if raw == "OWNER_ONLY" else re.findall(r'"(\w+)"', raw)
    entries.append((key, json.loads(label.group(1)), "admin" in sets, "member" in sets, "sensitive: true" in block))

if not entries:
    sys.exit("no permissions found")

def cs(s):
    return json.dumps(s)

out = ["// <auto-generated>",
       "// Generated by scripts/gen-permissions.py from packages/types/src/den/permissions.ts. Do not edit by hand.",
       "// </auto-generated>",
       "namespace WorkAI360.Api.Auth;",
       "",
       "public sealed record PermissionDefinition(string Key, string Label, bool AdminDefault, bool MemberDefault, bool Sensitive);",
       "",
       "public static partial class PermissionCatalog",
       "{",
       "    public static readonly IReadOnlyList<PermissionDefinition> All =",
       "    ["]
for key, label, admin, member, sensitive in entries:
    out.append(f"        new({cs(key)}, {cs(label)}, {str(admin).lower()}, {str(member).lower()}, {str(sensitive).lower()}),")
out += ["    ];", "}", ""]
dest = root / "360workai/src/WorkAI360.Api/Auth/PermissionCatalog.g.cs"
dest.write_text("\n".join(out))
print(f"{len(entries)} permissions: {sum(e[2] for e in entries)} on by default for admins, {sum(e[3] for e in entries)} for members, {sum(e[4] for e in entries)} sensitive")
